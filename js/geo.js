function norm(s) {
  return String(s || '').normalize('NFKC').replace(/[\s　()（）「」【】・]/g, '').replace(/(駅|バスターミナル|バスタ|バス停|乗り場|のりば|港|ターミナル|BT)$/i, '');
}

// 場所の名前 → { lat, lon, pref, name }（分からなければ null）
export function locate(name) {
  if (!name) return null;
  const n = norm(name);
  if (!n) return null;
  const cache = store.data.geoCache || {};
  if (cache[name]) return { ...cache[name], name, pref: '' };
  for (const e of INDEX) {
    if (e.key.length >= 2 && (n === e.key || n.includes(e.key))) return { lat: e.lat, lon: e.lon, pref: e.pref, name: e.primary };
  }
  if (cache[n]) return { ...cache[n], name, pref: '' };
  return null;
}

// 2点の距離（km）
export function km(a, b) {
  if (!a || !b) return null;
  const R = 6371, r = Math.PI / 180;
  const d1 = (b.lat - a.lat) * r, d2 = (b.lon - a.lon) * r;
  const x = Math.sin(d1 / 2) ** 2 + Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.sin(d2 / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(x));
}

// 乗り物ごとの所要時間の目安（分）。道のりは直線の 1.3 倍くらい
export function estMinutes(dist, type) {
  if (dist == null) return null;
  const road = dist * 1.3;
  switch (type) {
    case 'flight': return Math.round(45 + dist / 11);
    case 'shinkansen': return Math.round(10 + road / 3.2);
    case 'train': case 'subway': return Math.round(8 + road / 1.1);
    case 'bus': return Math.round(10 + road / 0.9);
    case 'taxi': return Math.round(8 + road / 0.75);
    case 'ferry': return Math.round(20 + road / 0.5);
    case 'ropeway': return Math.round(8 + road / 0.3);
    case 'walk': return Math.round(road * 13);
    default: return Math.round(10 + road / 1);
  }
}
// 距離に合う乗り物の候補
export function suggestType(dist, a, b) {
  if (dist == null) return 'train';
  if (dist < 1.2) return 'walk';
  // 海をまたぐ（北海道⇔本州・沖縄）は飛行機
  const isl = (x) => (x?.pref === '沖縄' ? 'oki' : x?.pref === '北海道' ? 'hok' : 'main');
  if (a && b && isl(a) !== isl(b) && !(dist < 250 && [a.name, b.name].some((n) => /函館|新函館北斗/.test(n || '')))) return 'flight';
  if (dist < 150) return 'train';
  // 新幹線が無い北海道（函館まわりを除く）の中は特急
  if (a?.pref === '北海道' && b?.pref === '北海道') return dist < 600 ? 'train' : 'flight';
  if (dist < 700) return 'shinkansen';
  return 'flight';
}

// 予定の「始まりの場所」と「終わりの場所」
export function startPlace(it) { return TRANSPORT.has(it.type) ? (it.from || '') : (it.address || it.title || ''); }
export function endPlace(it) { return TRANSPORT.has(it.type) ? (it.to || '') : (it.address || it.title || ''); }
export function locateItem(it, which = 'end') {
  if (it.lat && it.lon && !TRANSPORT.has(it.type)) return { lat: it.lat, lon: it.lon, name: it.title };
  const p = which === 'end' ? endPlace(it) : startPlace(it);
  return locate(p) || (!TRANSPORT.has(it.type) ? locate(it.title) : null);
}
